"""Utilities for converting Pydantic models into strict JSON Schemas for LLM APIs."""

from copy import deepcopy
from typing import Any

from pydantic import BaseModel


def _resolve_refs(node: Any, defs: dict[str, Any], seen: frozenset[str] = frozenset()) -> Any:
    """Recursively inline JSON Schema $ref pointers from $defs."""
    if isinstance(node, list):
        return [_resolve_refs(item, defs, seen) for item in node]
    if not isinstance(node, dict):
        return node

    if "$ref" in node:
        ref = node["$ref"]
        prefix = "#/$defs/"
        if isinstance(ref, str) and ref.startswith(prefix):
            name = ref[len(prefix) :]
            if name in defs and name not in seen:
                resolved = _resolve_refs(deepcopy(defs[name]), defs, seen | {name})
                siblings = {k: v for k, v in node.items() if k != "$ref"}
                if siblings and isinstance(resolved, dict):
                    resolved.update(_resolve_refs(siblings, defs, seen))
                return resolved

    return {k: _resolve_refs(v, defs, seen) for k, v in node.items()}


def _clean_strict_node(
    node: Any,
    *,
    exclude_fields: set[str],
    force_string_fields: set[str],
) -> Any:
    """Normalize resolved schema nodes for OpenAI/Mistral/Scaleway strict json_schema mode."""
    if isinstance(node, list):
        return [
            _clean_strict_node(item, exclude_fields=exclude_fields, force_string_fields=force_string_fields)
            for item in node
        ]
    if not isinstance(node, dict):
        return node

    cleaned: dict[str, Any] = {}
    for key, value in node.items():
        if key in {"title", "default"}:
            continue
        cleaned[key] = _clean_strict_node(
            value,
            exclude_fields=exclude_fields,
            force_string_fields=force_string_fields,
        )

    # Collapse single-element allOf wrappers generated by Pydantic when fields carry metadata.
    if list(cleaned.keys()) == ["allOf"] and isinstance(cleaned["allOf"], list) and len(cleaned["allOf"]) == 1:
        inner = cleaned["allOf"][0]
        if isinstance(inner, dict):
            return inner
    if "allOf" in cleaned and isinstance(cleaned["allOf"], list) and len(cleaned["allOf"]) == 1:
        inner = cleaned.pop("allOf")[0]
        if isinstance(inner, dict):
            merged = dict(inner)
            merged.update(cleaned)
            cleaned = merged

    if cleaned.get("type") == "object" and isinstance(cleaned.get("properties"), dict):
        props = {
            prop_name: _apply_field_override(prop_schema, prop_name, force_string_fields)
            for prop_name, prop_schema in cleaned["properties"].items()
            if prop_name not in exclude_fields
        }
        cleaned["properties"] = props
        cleaned["additionalProperties"] = False
        cleaned["required"] = list(props.keys())

    return cleaned


def _apply_field_override(prop_schema: Any, prop_name: str, force_string_fields: set[str]) -> Any:
    """Optionally force mixed string/int union fields (e.g. PESEL) to string|null for LLM output."""
    if prop_name not in force_string_fields or not isinstance(prop_schema, dict):
        return prop_schema

    has_null = any(isinstance(opt, dict) and opt.get("type") == "null" for opt in prop_schema.get("anyOf", []))
    result: dict[str, Any] = {}
    if "description" in prop_schema:
        result["description"] = prop_schema["description"]
    if has_null:
        result["anyOf"] = [{"type": "string"}, {"type": "null"}]
    else:
        result["type"] = "string"
    return result


def to_strict_json_schema(
    model_cls: type[BaseModel],
    *,
    exclude_fields: set[str] | None = None,
    force_string_fields: set[str] | None = None,
) -> dict[str, Any]:
    """Convert a Pydantic model into a self-contained strict JSON Schema."""
    raw_schema = model_cls.model_json_schema(by_alias=True)
    defs = raw_schema.pop("$defs", {})
    resolved = _resolve_refs(raw_schema, defs)
    return _clean_strict_node(
        resolved,
        exclude_fields=exclude_fields or set(),
        force_string_fields=force_string_fields or set(),
    )


def build_response_format(schema_name: str, strict_schema: dict[str, Any], *, strict: bool = True) -> dict[str, Any]:
    """Build an OpenAI-compatible `response_format` payload for structured JSON output."""
    return {
        "type": "json_schema",
        "json_schema": {
            "name": schema_name,
            "strict": strict,
            "schema": strict_schema,
        },
    }
